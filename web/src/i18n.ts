export type Language = 'en' | 'ko'

export const defaultLanguage: Language = 'en'

export function initialLanguage(): Language {
  try {
    return localStorage.getItem('gg-language') === 'ko' ? 'ko' : defaultLanguage
  } catch {
    return defaultLanguage
  }
}

